from fastapi import APIRouter, Depends, HTTPException, UploadFile, File, Form
from sqlmodel import Session, select
from typing import Optional
import uuid

from app.core.database import get_session
from app.api.dependencies import get_current_user
from app.models.user.user import User
from app.models.group.group import GroupMembership
from app.models.group.chat import GroupChatMessage
from app.services.cloud_storage import upload_file_to_r2

router = APIRouter(prefix="/api/v1/groups", tags=["Group Chat"])

@router.post("/{group_id}/chat/media", summary="Upload Media to Group Chat (WhatsApp style)")
async def upload_chat_media(
    group_id: str,
    file: UploadFile = File(..., description="The media file to upload"),
    client_message_id: str = Form(..., description="UUID generated by the mobile app to prevent duplicate sends"),
    media_type: str = Form(..., description="IMAGE, VIDEO, AUDIO, DOCUMENT, VOICE_NOTE"),
    message_text: Optional[str] = Form(None, description="Optional text caption for the media"),
    reply_to_message_id: Optional[int] = Form(None, description="ID of the message being replied to"),
    session: Session = Depends(get_session),
    current_user: User = Depends(get_current_user)
):
    # 1. Verify User is a member of the group
    membership = session.exec(
        select(GroupMembership).where(
            GroupMembership.group_id == group_id,
            GroupMembership.user_id == current_user.id,
            GroupMembership.status == "ACTIVE"
        )
    ).first()
    
    if not membership:
        raise HTTPException(status_code=403, detail="You must be an active member to send messages to this group.")
        
    # 2. Check if this client_message_id already exists to prevent duplicate uploads on retry
    existing_msg = session.exec(
        select(GroupChatMessage).where(GroupChatMessage.client_message_id == client_message_id)
    ).first()
    if existing_msg:
        return {"message": "Already uploaded", "data": existing_msg}

    # 3. Upload File to Cloudflare R2
    # Clean folder structure: chat-media/group_id/
    folder_path = f"chat-media/{group_id}"
    
    media_url = await upload_file_to_r2(file, folder=folder_path)
    if not media_url:
        raise HTTPException(status_code=500, detail="Failed to upload media to cloud storage.")
        
    # Get file size if available (FastAPI 0.100+)
    media_size_bytes = getattr(file, "size", None)
        
    # 4. Save Message to Database
    new_message = GroupChatMessage(
        client_message_id=client_message_id,
        group_id=group_id,
        sender_id=str(current_user.id),
        message_type="MEDIA",
        message_text=message_text,
        media_url=media_url,
        media_type=media_type,
        media_mime_type=file.content_type,
        media_size_bytes=media_size_bytes,
        reply_to_message_id=reply_to_message_id,
        status="SENT" # Successfully uploaded and registered in DB
    )
    
    session.add(new_message)
    try:
        session.commit()
        session.refresh(new_message)
    except Exception as e:
        session.rollback()
        raise HTTPException(status_code=500, detail="Failed to save message to database due to an internal error.")
        
    # 5. TODO: Trigger Websocket Event here to broadcast the new message to all connected clients in the group
    
    return {
        "message": "Media uploaded successfully",
        "data": new_message
    }

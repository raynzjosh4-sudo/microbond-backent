from fastapi import APIRouter, Depends, HTTPException, UploadFile, File, Form, BackgroundTasks
from sqlmodel import Session, select
from typing import Optional, List, Dict, Any, Union
import uuid
import io
import logging
from PIL import Image

from app.core.database import get_session
from app.api.dependencies import get_current_user
from app.models.user.user import User
from app.models.group.group import GroupMembership
from app.models.group.chat import GroupChatMessage
from app.models.group.settings import GroupGovernanceSettings
from app.services.cloud_storage import upload_file_to_r2
from app.services.websocket_manager import ws_manager
from app.services.push_notifications import notify_all_group_members

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/v1/groups", tags=["Group Chat"])

def _extract_image_dimensions(file_bytes: bytes) -> tuple[Optional[int], Optional[int], Optional[float]]:
    """Safely extracts width, height, and aspect ratio from image bytes."""
    try:
        with Image.open(io.BytesIO(file_bytes)) as img:
            w, h = img.size
            ratio = round(w / h, 3) if h > 0 else None
            return w, h, ratio
    except Exception:
        return None, None, None

@router.post("/{group_id}/chat/media", summary="Upload Media or Multi-Image Album to Group Chat")
async def upload_chat_media(
    group_id: str,
    background_tasks: BackgroundTasks,
    files: List[UploadFile] = File(..., description="One or more media files (images, videos, audio, documents)"),
    client_message_id: str = Form(..., description="Unique client UUID generated by the app"),
    media_type: str = Form("IMAGE", description="IMAGE, VIDEO, AUDIO, DOCUMENT, VOICE_NOTE"),
    message_text: Optional[str] = Form(None, description="Optional text caption for the media or album"),
    reply_to_message_id: Optional[str] = Form(None, description="ID or client_message_id of message being replied to"),
    session: Session = Depends(get_session),
    current_user: User = Depends(get_current_user)
):
    """
    High-performance media uploader supporting:
    - Single media uploads
    - Multi-file albums (e.g., 2 to 10 images selected at once)
    - Automatic width, height, and aspect_ratio calculation for instant UI rendering
    - Immediate WebSocket broadcast and push notifications
    """
    # 1. Verify User is a member of the group
    membership = session.exec(
        select(GroupMembership).where(
            GroupMembership.group_id == group_id,
            GroupMembership.user_id == current_user.id,
            GroupMembership.status == "ACTIVE"
        )
    ).first()
    
    if not membership:
        raise HTTPException(status_code=403, detail="You must be an active member to send messages to this group.")

    # 2. Check Governance Permissions: Only admins can send media if members_can_send_messages is false
    if membership.role != "ADMIN":
        gov_settings = session.exec(
            select(GroupGovernanceSettings).where(GroupGovernanceSettings.group_id == group_id)
        ).first()
        if gov_settings and not gov_settings.members_can_send_messages:
            raise HTTPException(
                status_code=403,
                detail="Only group admins can send messages in this group."
            )
        
    # 3. Check if this client_message_id already exists to prevent duplicate uploads on retry
    existing_msg = session.exec(
        select(GroupChatMessage).where(GroupChatMessage.client_message_id == client_message_id)
    ).first()
    if existing_msg:
        return {"message": "Already uploaded", "data": existing_msg}

    # 4. Upload Files to Cloudflare R2 and extract image metadata
    folder_path = f"chat-media/{group_id}"
    uploaded_attachments: List[Dict[str, Any]] = []

    primary_url = None
    primary_mime = None
    primary_size = None
    primary_width = None
    primary_height = None
    primary_ratio = None

    for idx, f in enumerate(files):
        # Read content into memory to extract dimensions
        content = await f.read()
        f_size = len(content)
        
        # Reset file cursor so upload_file_to_r2 can stream it
        f.file.seek(0)
        uploaded_url = await upload_file_to_r2(f, folder=folder_path)
        if not uploaded_url:
            logger.error(f"Failed to upload media file {f.filename}")
            continue

        w, h, ratio = None, None, None
        # Extract dimensions if image
        if (f.content_type and f.content_type.startswith("image/")) or media_type == "IMAGE":
            w, h, ratio = _extract_image_dimensions(content)

        attachment_info = {
            "attachment_id": str(uuid.uuid4()),
            "url": uploaded_url,
            "filename": f.filename,
            "media_type": media_type,
            "mime_type": f.content_type or "application/octet-stream",
            "size_bytes": f_size,
            "width": w,
            "height": h,
            "aspect_ratio": ratio
        }
        uploaded_attachments.append(attachment_info)

        # Set first file as primary
        if idx == 0:
            primary_url = uploaded_url
            primary_mime = f.content_type or "application/octet-stream"
            primary_size = f_size
            primary_width = w
            primary_height = h
            primary_ratio = ratio

    if not uploaded_attachments:
        raise HTTPException(status_code=500, detail="Failed to upload media to cloud storage.")

    # 5. Sanitize and resolve reply_to_message_id
    reply_id: Optional[uuid.UUID] = None
    if reply_to_message_id is not None:
        raw_val = str(reply_to_message_id).strip()
        if raw_val and raw_val != "0" and raw_val.lower() != "string" and raw_val.lower() != "null":
            try:
                candidate_uuid = uuid.UUID(raw_val)
                ref_msg = session.exec(
                    select(GroupChatMessage).where(GroupChatMessage.id == candidate_uuid)
                ).first()
                if ref_msg:
                    reply_id = ref_msg.id
            except ValueError:
                candidate_uuid = None

            if reply_id is None:
                ref_msg = session.exec(
                    select(GroupChatMessage).where(GroupChatMessage.client_message_id == raw_val)
                ).first()
                if ref_msg:
                    reply_id = ref_msg.id
        
    # 6. Save Message to Database
    new_message = GroupChatMessage(
        client_message_id=client_message_id,
        group_id=group_id,
        sender_id=str(current_user.id),
        message_type="MEDIA",
        message_text=message_text,
        media_url=primary_url,
        media_type=media_type,
        media_mime_type=primary_mime,
        media_size_bytes=primary_size,
        media_width=primary_width,
        media_height=primary_height,
        aspect_ratio=primary_ratio,
        attachments=uploaded_attachments,
        reply_to_message_id=reply_id,
        status="SENT"
    )
    
    session.add(new_message)
    try:
        session.commit()
        session.refresh(new_message)
    except Exception as e:
        session.rollback()
        logger.exception(f"Failed to save media message in group {group_id}: {e}")
        raise HTTPException(status_code=500, detail=f"Failed to save message to database: {str(e)}")
        
    # 7. Broadcast over WebSocket to all members in real-time
    await ws_manager.broadcast_to_group(
        group_id,
        {
            "event_type": "NEW_MESSAGE",
            "message": new_message.model_dump(mode="json")
        },
        exclude_user_id=str(current_user.id)
    )

    # 8. Trigger offline push notification
    title = f"New media from {current_user.full_name}"
    count = len(uploaded_attachments)
    body = message_text or (f"Sent {count} photos" if count > 1 else f"Sent a photo")
    background_tasks.add_task(
        notify_all_group_members,
        group_id=group_id,
        sender_id=str(current_user.id),
        title=title,
        body=body,
        data={"type": "chat_message", "group_id": group_id, "message_id": str(new_message.id)}
    )
    
    return {
        "message": "Media uploaded successfully",
        "data": new_message
    }
